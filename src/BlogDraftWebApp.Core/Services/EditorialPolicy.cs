namespace BlogDraftWebApp.Core.Services;

internal static class EditorialPolicy
{
    internal const string SystemSectionTitle = "[編集方針: 入力保持・限定補足]";

    internal const string Text = """
入力は、著者が記事に含めたい内容を選んだ原稿のラフとして扱う。
記載された主張・事実・経験・具体例・留保・参照情報を、独自の重要度判断で削除しない。
論理展開が示されている場合は、その関係と強調を尊重する。単なる列挙の場合は、内容を保持したまま読みやすく整理する。
同義の重複を統合したり、箇条書きを接続文に変えたりしてよいが、異なる意味は残す。
補足は、入力のどの内容を理解・判断・再現するために必要か説明できる範囲に限る。
読者にとって既知の通常操作や今回と変わらない部分は圧縮し、今回違った部分、迷った部分、判断や結果に効いた部分を詳しくする。ただし、入力に明示された内容を「既知だから」という理由で消さない。
入力にない独立した論点、別用途、網羅的な機能説明を追加しない。
未確認の原因や試していない範囲を一般知識で埋めず、経験・見立ての確度を変えない。
URL・コード・コマンド・数値・条件と、それらの役割を保持する。リンク先へ委ねた説明は勝手に本文へ展開しない。
箇条書きや列挙の形式を変えてよいが、そこに含まれる意味・論理関係・強調・具体値・参照を保つ。入力にない独立論点や未確認の固有名詞・比較対象を補わない。
入力の意味が本文から欠けていないか、本文に不要な説明を追加していないかを両方向で確認する。
文字数・見出し数・ポイント数の下限や、章ごとの均等な分量を目標にしない。
この方針と矛盾する文体カードの規則は、この生成タスクでは適用しない。
""";
}
